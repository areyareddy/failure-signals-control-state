"""Emit LaTeX macros for the S4 targeted-cap replication from the frozen analysis output.

Reads audit/cap_policy_analysis.json (written by scripts/s56_cap_policy_analysis.py, whose
hash is recorded in audit/cap_policy_hashes.json) and writes cap_macros.tex.

Per the project rule that prose numbers are never hand-typed: every S4 figure in the paper
must come from a macro defined here. This script computes nothing -- it only formats what
the frozen analysis already decided. If a quantity is not in the analysis JSON, it does not
belong in the paper.

Fails loudly rather than emitting a plausible-looking wrong file:
  * missing analysis JSON            -> exit 2
  * no complete block                -> exit 3
  * prefix-gate violations present   -> still emits, but sets \CapPrefixViolations and
                                        \CapPrefixClean{false}; the paper must report it
  * energy coverage failures         -> \CapEnergyCoverageFailures is non-zero and the
                                        energy macros are still emitted unrounded, because
                                        the specification forbids interpolating a gap
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PAPER = HERE.parent
# the analysis lives in the experiment root, four levels up from the paper directory
EXP = PAPER.parent.parent
ANALYSIS = EXP / "audit/cap_policy_analysis.json"
OUT = PAPER / "cap_macros.tex"


def tex_num(x, dp=0, signed=False):
    if x is None:
        return r"\textit{n/a}"
    if isinstance(x, int) or dp == 0:
        s = f"{round(float(x)):,d}"
    else:
        s = f"{float(x):,.{dp}f}"
    if signed and float(x) > 0 and not s.startswith("+"):
        s = "+" + s
    return s


def pct(x, dp=1, signed=False):
    if x is None:
        return r"\textit{n/a}"
    return tex_num(x, dp, signed) + r"\%"


def pts(x, dp=1):
    """A percentage-point effect, given as a fraction in the analysis JSON."""
    if x is None:
        return r"\textit{n/a}"
    return f"{100 * float(x):+.{dp}f}"


def ci_pts(lohi, dp=1):
    if not lohi:
        return r"\textit{n/a}"
    lo, hi = lohi
    return f"[{100 * float(lo):+.{dp}f}, {100 * float(hi):+.{dp}f}]"


def main() -> int:
    # --analysis/--out exist so the emitter can be exercised on a synthetic fixture before
    # the real run lands; the defaults are the only paths used for the paper.
    analysis, out = ANALYSIS, OUT
    argv = sys.argv[1:]
    for flag, target in (("--analysis", "a"), ("--out", "o")):
        if flag in argv:
            v = Path(argv[argv.index(flag) + 1])
            if target == "a":
                analysis = v
            else:
                out = v

    design_only = "--design-only" in argv

    # --- design constants: frozen before generation, so they are available (and final)
    # --- before any outcome exists. Sourced from the hashed plan and seed registry.
    D = []
    plan = json.loads((EXP / "audit/cap_policy_plan.json").read_text(encoding="utf-8"))
    reg = json.loads((EXP / "audit/seed_registry.json").read_text(encoding="utf-8"))
    n_gen = sum(s["n_roots"] for s in plan["execution_order"])
    n_aff = len(plan["truncated_roots"])
    n_un = len(plan["unaffected_roots"])
    D.append(r"\newcommand{\CapLongCap}{%s}" % tex_num(plan["long_cap"]))
    D.append(r"\newcommand{\CapShortCap}{%s}" % tex_num(plan["short_cap"]))
    D.append(r"\newcommand{\CapRoots}{%s}" % tex_num(n_aff + n_un))
    D.append(r"\newcommand{\CapAffectedRoots}{%s}" % tex_num(n_aff))
    D.append(r"\newcommand{\CapUnaffectedRoots}{%s}" % tex_num(n_un))
    D.append(r"\newcommand{\CapGenerations}{%s}" % tex_num(n_gen))
    D.append(r"\newcommand{\CapCohorts}{%s}" % tex_num(len(plan["execution_order"])))
    D.append(r"\newcommand{\CapSeedBases}{%s}" %
             ", ".join(tex_num(b) for b in plan["bases"]))
    D.append(r"\newcommand{\CapSeedsKnown}{%s}" % tex_num(reg["n_all_known_seeds"]))
    D.append(r"\newcommand{\CapSeedsLocal}{%s}" % tex_num(reg["n_local_seeds"]))
    D.append(r"\newcommand{\CapSeedsPredecessor}{%s}" % tex_num(reg["n_colm_seeds"]))
    D.append(r"\newcommand{\CapPredecessorScanned}{%s}" % tex_num(reg["colm_files_scanned"]))
    D.append(r"\newcommand{\CapSeedCollisions}{%s}" % tex_num(len(reg["collisions"])))
    D.append(r"\newcommand{\CapChunkSize}{%s}" % tex_num(plan["chunk_size"]))

    if design_only:
        hdr = ["% GENERATED by scripts/build_cap_macros.py --design-only.",
               "% Design constants only, from the frozen plan and seed registry.",
               "% Result macros appear once s56_cap_policy_analysis.py has run.", ""]
        out.write_text("\n".join(hdr + D) + "\n", encoding="utf-8")
        print(f"wrote {out}  ({len(D)} design macros, no results yet)")
        return 0

    if not analysis.exists():
        print(f"ERROR: {analysis} does not exist. Run scripts/s56_cap_policy_analysis.py "
              f"in {EXP} first.", file=sys.stderr)
        return 2
    a = json.loads(analysis.read_text(encoding="utf-8"))

    blocks = a.get("complete_blocks") or []
    if not blocks:
        print("ERROR: the analysis reports no complete block "
              f"({a.get('reason', 'no reason given')}). Per the specification a partly "
              "generated block is reported as not run, never as a subset. No macros "
              "written.", file=sys.stderr)
        return 3

    L = []
    add = L.append
    add("% GENERATED by scripts/build_cap_macros.py from audit/cap_policy_analysis.json,")
    add("% audit/cap_policy_plan.json and audit/seed_registry.json.")
    add("% Do not edit by hand. Every S4 number in the paper resolves through this file.")
    add("")
    add("% --- design constants, frozen before generation ---")
    L.extend(D)
    add("")
    add("% --- observed results, from the frozen analysis ---")

    # --- scope -------------------------------------------------------------
    add(r"\newcommand{\CapBlocks}{%s}" % tex_num(len(blocks)))
    add(r"\newcommand{\CapBlockList}{%s}" % ", ".join(str(b) for b in blocks))
    add(r"\newcommand{\CapRowsSeen}{%s}" % tex_num(a.get("n_rows_seen")))
    add(r"\newcommand{\CapIncomplete}{%s}" % tex_num(a.get("n_incomplete")))

    # --- integrity: the prefix gate ---------------------------------------
    pg = a.get("prefix_gate", {})
    nviol = len(pg.get("violations", []))
    add(r"\newcommand{\CapPrefixChecked}{%s}" % tex_num(pg.get("checked")))
    add(r"\newcommand{\CapPrefixEqual}{%s}" % tex_num(pg.get("equal_ok")))
    add(r"\newcommand{\CapPrefixPrefix}{%s}" % tex_num(pg.get("prefix_ok")))
    add(r"\newcommand{\CapPrefixViolations}{%s}" % tex_num(nviol))
    add(r"\newcommand{\CapPrefixClean}{%s}" % ("true" if nviol == 0 else "false"))
    add("")

    # --- yield, aggregate over blocks (root-clustered) ---------------------
    agg = a.get("aggregate", {})
    for key, name in (("all40", "AllForty"), ("affected15", "AffectedFifteen")):
        e = agg.get(key)
        if not e:
            continue
        add(r"\newcommand{\Cap%sTheorems}{%s}" % (name, tex_num(e.get("n_theorems"))))
        add(r"\newcommand{\Cap%sEffectPts}{%s}" % (name, pts(e.get("mean_effect"))))
        add(r"\newcommand{\Cap%sCI}{%s}" % (name, ci_pts(e.get("ci95"))))
    add("")

    # --- discordance, and whether the bootstrap interval is degenerate ------
    # A zero-width interval here means the resample found no discordance to
    # propagate, not that the null was estimated precisely. Emit the count and a
    # rule-of-three bound clustered on theorem so the prose can say so.
    disc = 0
    for b in blocks:
        e = a["per_block"][str(b)] if str(b) in a["per_block"] else a["per_block"][b]
        v = e.get("affected15", {})
        disc += int(v.get("x_only") or 0) + int(v.get("y_only") or 0)
    n_aff = int((agg.get("affected15") or {}).get("n_theorems") or 0)
    degenerate = all(
        list((agg.get(k) or {}).get("ci95") or [1]) == [0.0, 0.0]
        for k in ("all40", "affected15")
    )
    _w = {1: "one", 2: "two", 3: "three", 4: "four", 5: "five", 6: "six"}
    add(r"\newcommand{\CapBlocksWord}{%s}" % _w.get(len(blocks), str(len(blocks))))
    add(r"\newcommand{\CapDiscordantPairs}{%s}" % tex_num(disc))
    add(r"\newcommand{\CapCIDegenerate}{%s}" % ("true" if degenerate else "false"))
    if n_aff:
        add(r"\newcommand{\CapDiscordantUpperPct}{%s}" % pct(300.0 / n_aff, 0))
    add("")

    # --- yield and cost, per block ----------------------------------------
    words = {1: "One", 2: "Two", 3: "Three", 4: "Four", 5: "Five", 6: "Six"}
    tok_saved_pcts, j_saved_pcts, wall_saved_pcts = [], [], []
    for b in blocks:
        w = words.get(int(b), str(b))
        e = a["per_block"][str(b)] if str(b) in a["per_block"] else a["per_block"][b]
        for key, nm in (("all40", "AllForty"), ("affected15", "AffectedFifteen")):
            v = e.get(key, {})
            add(r"\newcommand{\CapBlock%s%sTargeted}{%s}"
                % (w, nm, tex_num(v.get("targeted_verified"))))
            add(r"\newcommand{\CapBlock%s%sLong}{%s}"
                % (w, nm, tex_num(v.get("long_verified"))))
            add(r"\newcommand{\CapBlock%s%sEffectPts}{%s}"
                % (w, nm, pts(v.get("effect"))))
            add(r"\newcommand{\CapBlock%s%sCI}{%s}" % (w, nm, ci_pts(v.get("ci95"))))
            add(r"\newcommand{\CapBlock%s%sP}{%s}"
                % (w, nm, tex_num(v.get("p_exact_mcnemar"), 3)))
            add(r"\newcommand{\CapBlock%s%sDiscordant}{%s/%s}"
                % (w, nm, tex_num(v.get("x_only")), tex_num(v.get("y_only"))))
        c = e.get("cost", {})
        add(r"\newcommand{\CapBlock%sLongTokens}{%s}" % (w, tex_num(c.get("long_tokens"))))
        add(r"\newcommand{\CapBlock%sTargetedTokens}{%s}"
            % (w, tex_num(c.get("targeted_tokens"))))
        add(r"\newcommand{\CapBlock%sTokensSaved}{%s}" % (w, tex_num(c.get("tokens_saved"))))
        add(r"\newcommand{\CapBlock%sTokensSavedPct}{%s}"
            % (w, pct(c.get("tokens_saved_pct"), 1)))
        add(r"\newcommand{\CapBlock%sWallSavedPct}{%s}"
            % (w, pct(c.get("wall_saved_pct"), 1)))
        if c.get("tokens_saved_pct") is not None:
            tok_saved_pcts.append(float(c["tokens_saved_pct"]))
        if c.get("wall_saved_pct") is not None:
            wall_saved_pcts.append(float(c["wall_saved_pct"]))

        en = (a.get("energy", {}).get("per_block", {}).get(str(b))
              or a.get("energy", {}).get("per_block", {}).get(b) or {})
        add(r"\newcommand{\CapBlock%sLongJoules}{%s}" % (w, tex_num(en.get("long_j"))))
        add(r"\newcommand{\CapBlock%sTargetedJoules}{%s}"
            % (w, tex_num(en.get("targeted_j"))))
        add(r"\newcommand{\CapBlock%sJoulesSavedPct}{%s}"
            % (w, pct(en.get("joules_saved_pct"), 1)))
        add(r"\newcommand{\CapBlock%sEnergyFailures}{%s}" % (w, tex_num(en.get("n_fail"))))
        if en.get("joules_saved_pct") is not None:
            j_saved_pcts.append(float(en["joules_saved_pct"]))
        add("")

    # --- ranges across blocks, for prose that must not pool ----------------
    def rng(vals, dp=1):
        if not vals:
            return r"\textit{n/a}"
        lo, hi = f"{min(vals):,.{dp}f}", f"{max(vals):,.{dp}f}"
        if lo == hi:  # blocks agree to the printed precision; a range would be noise
            return lo + r"\%"
        return f"{lo}--{hi}" + r"\%"

    add(r"\newcommand{\CapTokensSavedRange}{%s}" % rng(tok_saved_pcts))
    add(r"\newcommand{\CapWallSavedRange}{%s}" % rng(wall_saved_pcts))
    add(r"\newcommand{\CapJoulesSavedRange}{%s}" % rng(j_saved_pcts))

    en = a.get("energy", {})
    add(r"\newcommand{\CapEnergyCoverageFailures}{%s}"
        % tex_num(en.get("coverage_failures")))
    add(r"\newcommand{\CapEnergyBranchesMeasured}{%s}"
        % tex_num(en.get("branches_measured")))

    # absolute energy, so the paper can report receipts and not only percentages
    _pb = en.get("per_block", {})
    _lj = sum(v.get("long_j", 0.0) for v in _pb.values())
    _tj = sum(v.get("targeted_j", 0.0) for v in _pb.values())
    _rb = len(blocks) * int((agg.get("all40") or {}).get("n_theorems") or 0)
    _sh = len(blocks) * (int((agg.get("all40") or {}).get("n_theorems") or 0)
                         - int((agg.get("affected15") or {}).get("n_theorems") or 0))
    add(r"\newcommand{\CapSharedArms}{%s}" % tex_num(_sh))
    add(r"\newcommand{\CapLongKJ}{%s}" % tex_num(round(_lj / 1000)))
    add(r"\newcommand{\CapTargetedKJ}{%s}" % tex_num(round(_tj / 1000)))
    add(r"\newcommand{\CapKJSaved}{%s}" % tex_num(round((_lj - _tj) / 1000)))
    if _rb:
        add(r"\newcommand{\CapJoulesPerRootLong}{%s}" % tex_num(round(_lj / _rb)))
        add(r"\newcommand{\CapJoulesPerRootTargeted}{%s}" % tex_num(round(_tj / _rb)))
    ib = en.get("idle_baseline") or {}
    add(r"\newcommand{\CapIdleWatts}{%s}" % tex_num(ib.get("mean_power_w"), 1))
    add("")
    add(r"\newcommand{\CapEquivalenceClaim}{%s}"
        % ("true" if a.get("equivalence_claim") else "false"))

    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out}  ({len(L)} lines, {len(blocks)} complete block(s))")
    if nviol:
        print(f"WARNING: {nviol} prefix-gate violation(s). Per spec 9.4 this is a FINDING "
              f"and must be reported in the paper, not silently omitted.", file=sys.stderr)
    if en.get("coverage_failures"):
        print(f"WARNING: {en['coverage_failures']} branch(es) lack complete telemetry; "
              f"their energy claim fails and must not be interpolated.", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
