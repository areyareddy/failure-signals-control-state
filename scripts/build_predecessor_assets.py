#!/usr/bin/env python3
"""Build imported scheduler assets from copied, immutable predecessor results.

The script intentionally reads only files under provenance/predecessor and writes only
LaTeX fragments and a digest manifest inside this paper directory.
"""

from __future__ import annotations

import hashlib
import json
import math
from pathlib import Path
from statistics import median


ROOT = Path(__file__).resolve().parents[1]
PROV = ROOT / "provenance" / "predecessor"
TABLES = ROOT / "tables"


def load(name: str):
    return json.loads((PROV / name).read_text(encoding="utf-8"))


def pct(x: float, digits: int = 1) -> str:
    s = f"{100.0 * x:.{digits}f}"
    return ("$-$" + s[1:] if s.startswith("-") else s) + "\\%"


def tex_escape(text: str) -> str:
    return text.replace("_", "\\_")


def macro(name: str, value: str) -> str:
    return f"\\newcommand{{\\{name}}}{{{value}}}"


def main() -> None:
    TABLES.mkdir(exist_ok=True)

    b1 = load("transfer_analysis_validation_block1.json")
    b2 = load("transfer_analysis_goedel_block2.json")
    k1 = load("transfer_analysis_kimina.json")
    k2 = load("transfer_analysis_kimina_block2.json")
    ds = load("transfer_analysis_deepseek.json")
    a1 = load("ablation_goedel_block1.json")
    a2 = load("ablation_goedel_block2.json")
    boot = load("scheduler_bootstrap.json")
    retry = load("failure_class_retryability.json")
    split = load("minif2f_split.json")
    budget = load("scheduler_budget_slices.json")
    e2e = load("end_to_end_accounting.json")
    assert e2e["status"] == "cpu_exact_replay_passed"
    wall = {
        "goedel_block1": load("wallclock_block1.json"),
        "goedel_block2": load("wallclock_goedel_block2.json"),
        "kimina_block1": load("wallclock_kimina.json"),
        "kimina_block2": load("wallclock_kimina_block2.json"),
        "deepseek": load("wallclock_deepseek.json"),
    }

    b1_s = b1["primary"]["savings"]
    b2_s = b2["primary"]["savings"]
    # Section 4.1 reports the DEVELOPMENT ledger. The frozen rules were fit on the 43
    # development roots alone, so the 83-root ledger inherited from the predecessor is
    # descriptive only and belongs in the appendix. s60_dev_retryability.py recomputes
    # both from the predecessor's recorded draws and asserts that the shipped frozen
    # class order equals the development refit and differs from the all-root refit --
    # the evidence that the all-root ledger cannot have selected the policy.
    devret = load("dev_retryability.json")
    dv = devret["derived"]
    dev_rows = devret["ledger_dev43"]
    all_rows = devret["ledger_all83"]
    assert devret["reproduces_published_83_root_table"], \
        "recomputation no longer reproduces the inherited 83-root table"
    assert dv["frozen_matches_dev_fit"] and not dv["frozen_matches_all_fit"], \
        "frozen class order no longer separates the development and all-root fits"

    def cell(rows, cls):
        return next(r for r in rows if r["class"] == cls)

    # Attempt-level Wilson upper bound on the development timeout cell. Those attempts
    # cluster within few roots, so the paper labels it descriptive and relies on
    # draw-order parity rather than this interval alone.
    ratio = dv["dev_retry_spread"]
    timeout_wilson_upper = dv["dev_timeout_wilson_upper"]
    mb1, mb2 = budget["blocks"]["block1"], budget["blocks"]["block2"]

    # Plan-exhaustion comparison: what each policy spends when both simply run out of
    # eligible actions, with no tokens-to-target endpoint involved. Solve parity at that
    # point is asserted, because the saving is only meaningful at equal yield.
    exhaust = {}
    for name, blk in (("block1", mb1), ("block2", mb2)):
        row = next(r for r in blk["matched_budget_slices"]
                   if abs(r["fraction_uniform_full_spend"] - 1.0) < 1e-9)
        assert row["uniform_solves"] == row["rules_solves"], (
            f"{name}: policies do not reach equal solves at plan exhaustion")
        uniform_tok, rules_tok = row["budget_tokens"], row["rules_tokens_issued"]
        exhaust[name] = {"uniform_tokens": uniform_tok, "rules_tokens": rules_tok,
                         "solves": row["uniform_solves"],
                         "savings": 1 - rules_tok / uniform_tok}
    macros = [
        "% Generated by scripts/build_predecessor_assets.py. Do not edit by hand.",
        macro("SchedRoots", str(b1["n_theorems"])),
        macro("SchedDrawsPerRoot", "4"),
        macro("SchedBOneSolves", str(b1["primary"]["uniform_solves"])),
        macro("SchedBTwoSolves", str(b2["primary"]["uniform_solves"])),
        macro("SchedBOneSavings", pct(b1_s)),
        macro("SchedBTwoSavings", pct(b2_s)),
        macro("SchedBOneTokensUniform", f"{b1['primary']['Tu']:,}"),
        macro("SchedBOneTokensRules", f"{b1['primary']['T_rules']:,}"),
        macro("SchedBTwoTokensUniform", f"{b2['primary']['Tu']:,}"),
        macro("SchedBTwoTokensRules", f"{b2['primary']['T_rules']:,}"),
        macro("SchedBOneParity", f"{round(24*b1['orderings_summary']['rules']['reach_frac'])}/24"),
        macro("SchedBTwoParity", f"{round(24*b2['orderings_summary']['rules']['reach_frac'])}/24"),
        macro("SchedBOneOrderMedian", pct(b1["orderings_summary"]["rules"]["savings_median"])),
        macro("SchedBTwoOrderMedian", pct(b2["orderings_summary"]["rules"]["savings_median"])),
        macro("SchedBOneBoot", f"{pct(boot['goedel_block1']['median_savings'])} [{pct(boot['goedel_block1']['ci_low'])}, {pct(boot['goedel_block1']['ci_high'])}]"),
        macro("SchedBTwoBoot", f"{pct(boot['goedel_block2']['median_savings'])} [{pct(boot['goedel_block2']['ci_low'])}, {pct(boot['goedel_block2']['ci_high'])}]"),
        macro("SchedRetrySpread", f"${ratio:.1f}\\times$"),
        macro("SchedCoarseBOne", pct(a1["variants"]["coarse"]["primary_savings"])),
        macro("SchedCoarseBTwo", pct(a2["variants"]["coarse"]["primary_savings"])),
        macro("SchedTimeBOne", pct(1 - wall["goedel_block1"]["policies"]["rules"]["total_s"] / wall["goedel_block1"]["policies"]["uniform"]["total_s"])),
        macro("SchedTimeBTwo", pct(1 - wall["goedel_block2"]["policies"]["rules"]["total_s"] / wall["goedel_block2"]["policies"]["uniform"]["total_s"])),
        macro("SchedKiminaOneSavings", pct(k1["primary"]["savings"])),
        macro("SchedKiminaTwoSavings", pct(k2["primary"]["savings"])),
        macro("SchedKiminaOneTime", pct(1 - wall["kimina_block1"]["policies"]["rules"]["total_s"] / wall["kimina_block1"]["policies"]["uniform"]["total_s"])),
        macro("SchedKiminaTwoTime", pct(1 - wall["kimina_block2"]["policies"]["rules"]["total_s"] / wall["kimina_block2"]["policies"]["uniform"]["total_s"])),
        macro("SchedDeepSeekSavings", pct(ds["primary"]["savings"])),
        macro("SchedTimeoutWilsonUpper", pct(timeout_wilson_upper)),
        macro("SchedBOneUnissued", f"{mb1['unissued_at_uniform_full_spend']:,}"),
        macro("SchedBTwoUnissued", f"{mb2['unissued_at_uniform_full_spend']:,}"),
        # Savings at plan exhaustion rather than at the tokens-to-target endpoint. The
        # equal-yield endpoint in Table 1 is an evaluation-only construct -- it needs
        # uniform's eventual solve count, which a deployed controller never observes -- so
        # the paper also reports what both policies spend when simply run to exhaustion.
        macro("SchedBOneExhaustSavings", pct(exhaust["block1"]["savings"])),
        macro("SchedBTwoExhaustSavings", pct(exhaust["block2"]["savings"])),
        macro("SchedBOneUniformFullSpend", f"{exhaust['block1']['uniform_tokens']:,}"),
        macro("SchedBTwoUniformFullSpend", f"{exhaust['block2']['uniform_tokens']:,}"),
        macro("SchedBOneRulesIssued", f"{exhaust['block1']['rules_tokens']:,}"),
        macro("SchedBTwoRulesIssued", f"{exhaust['block2']['rules_tokens']:,}"),
        macro("SchedCalibratedBOne", pct(mb1["calibrated_savings_vs_uniform_tokens_to_target"])),
        macro("SchedCalibratedBTwo", pct(mb2["calibrated_savings_vs_uniform_tokens_to_target"])),
        macro("SchedStageOneCalls", f"{e2e['stage1']['calls']:,}"),
        macro("SchedStageOneTokens", f"{e2e['stage1']['completion_tokens']:,}"),
        macro("SchedStageOneVerified", str(e2e["stage1"]["verified"])),
        # --- development retryability ledger (Section 4.1) and the all-root contrast
        macro("SchedDevRoots", str(cell(dev_rows, "all")["theorems"])),
        macro("SchedDevAttempts", str(cell(dev_rows, "all")["attempts"])),
        macro("SchedAllRoots", str(cell(all_rows, "all")["theorems"])),
        macro("SchedAllAttempts", str(cell(all_rows, "all")["attempts"])),
        macro("SchedDevUnknownRescues", str(cell(dev_rows, "unknown_identifier")["rescues"])),
        macro("SchedDevUnknownAttempts", str(cell(dev_rows, "unknown_identifier")["attempts"])),
        macro("SchedDevUnknownTokens", f"{cell(dev_rows, 'unknown_identifier')['mean_completion_tokens']:,}"),
        macro("SchedDevUnknownRho", f"{cell(dev_rows, 'unknown_identifier')['rescues_per_token_e5']:.2f}"),
        macro("SchedDevTruncRescues", str(cell(dev_rows, "truncated")["rescues"])),
        macro("SchedDevTruncAttempts", str(cell(dev_rows, "truncated")["attempts"])),
        macro("SchedDevTruncTokens", f"{cell(dev_rows, 'truncated')['mean_completion_tokens']:,}"),
        macro("SchedDevTruncRho", f"{cell(dev_rows, 'truncated')['rescues_per_token_e5']:.2f}"),
        macro("SchedDevTimeoutRescues", str(cell(dev_rows, "timeout")["rescues"])),
        macro("SchedDevTimeoutAttempts", str(cell(dev_rows, "timeout")["attempts"])),
        macro("SchedDevTimeoutTokens", f"{cell(dev_rows, 'timeout')['mean_completion_tokens']:,}"),
        macro("SchedDevTimeoutRoots", str(dv["dev_timeout_roots"])),
        macro("SchedRerankClass", dv["rank_disagreement_class"].replace("_", " ")),
        macro("SchedRerankDevRank", str(dv["rank_in_dev_fit"])),
        macro("SchedRerankAllRank", str(dv["rank_in_all_fit"])),
        macro("SchedRerankedClasses", str(dv["n_classes_reranked"])),
        macro("SchedClassCount", str(len(dv["frozen_class_order"]))),
        macro("MiniFTwoFTest", str(split["minif2f_test_statements"])),
        macro("MiniFTwoFUsed", str(split["evaluation_theorems_used"])),
        macro("MiniFTwoFExcluded", str(split["excluded_inspected"])),
    ]
    for key, word in (("block1", "One"), ("block2", "Two")):
        block = e2e["blocks"][key]
        macros.extend([
            macro(f"SchedPipeline{word}Verified", f"{block['total_verified_of_202']}/202"),
            macro(f"SchedPipeline{word}UniformCalls", f"{block['uniform']['pipeline_calls']:,}"),
            macro(f"SchedPipeline{word}RulesCalls", f"{block['rules']['pipeline_calls']:,}"),
            macro(f"SchedPipeline{word}CallsAvoided", f"{block['calls_avoided']:,}"),
            macro(f"SchedPipeline{word}UniformTokens", f"{block['uniform']['pipeline_completion_tokens']:,}"),
            macro(f"SchedPipeline{word}RulesTokens", f"{block['rules']['pipeline_completion_tokens']:,}"),
            macro(f"SchedPipeline{word}Savings", pct(block["pipeline_completion_token_savings_fraction"])),
            macro(f"SchedPipeline{word}UniformCallsPerVerified",
                  f"{block['uniform']['pipeline_calls_per_verified']:.2f}"),
            macro(f"SchedPipeline{word}RulesCallsPerVerified",
                  f"{block['rules']['pipeline_calls_per_verified']:.2f}"),
        ])
    (ROOT / "predecessor_macros.tex").write_text("\n".join(macros) + "\n", encoding="utf-8")

    block_rows = []
    for label, data, key in [
        ("Seed block 1", b1, "goedel_block1"),
        ("Seed block 2", b2, "goedel_block2"),
    ]:
        w = wall[key]["policies"]
        time_save = 1 - w["rules"]["total_s"] / w["uniform"]["total_s"]
        block_rows.append(
            f"{label} & {data['primary']['uniform_solves']}/{data['n_theorems']} & "
            f"{data['primary']['Tu']:,} & {data['primary']['T_rules']:,} & "
            f"{pct(data['primary']['savings'])} & {pct(time_save)} & "
            f"{round(24*data['orderings_summary']['rules']['reach_frac'])}/24 \\\\"
        )
    (TABLES / "scheduler_blocks.tex").write_text("\n".join(block_rows) + "\n", encoding="utf-8")

    transfer_rows = []
    for label, data, key in [
        ("Goedel block 1", b1, "goedel_block1"),
        ("Goedel block 2", b2, "goedel_block2"),
        ("Kimina block 1", k1, "kimina_block1"),
        ("Kimina block 2", k2, "kimina_block2"),
        ("DeepSeek", ds, "deepseek"),
    ]:
        w = wall[key]["policies"]
        time_save = 1 - w["rules"]["total_s"] / w["uniform"]["total_s"]
        costly = data["classes"].get("truncated", 0) + data["classes"].get("timeout", 0)
        transfer_rows.append(
            f"{label} & {data['n_theorems']} & {costly} & {data['primary']['uniform_solves']} & "
            f"{pct(data['primary']['savings'])} & {pct(time_save)} \\\\"
        )
    (TABLES / "scheduler_transfer.tex").write_text("\n".join(transfer_rows) + "\n", encoding="utf-8")

    ablation_rows = []
    labels = [
        ("timeout_only", "Skip timeout"),
        ("trunccap_only", "Cap truncation"),
        ("coarse", "Both coarse clauses"),
        ("classorder", "Class ordering only"),
        ("rules", "Full rules"),
    ]
    for key, label in labels:
        v1, v2 = a1["variants"][key], a2["variants"][key]
        ablation_rows.append(
            f"{label} & {pct(v1['primary_savings'])} & {v1['parity_orderings']}/24 & "
            f"{pct(v2['primary_savings'])} & {v2['parity_orderings']}/24 \\\\"
        )
    (TABLES / "scheduler_ablation.tex").write_text("\n".join(ablation_rows) + "\n", encoding="utf-8")

    # Table 3 is the development ledger; the all-root ledger is an appendix contrast.
    # Both are emitted from the same recomputation so they cannot drift apart.
    def retry_table(rows):
        out = []
        for row in rows:
            out.append(
                f"{tex_escape(row['class'].replace('_', ' '))} & {row['theorems']} & "
                f"{row['attempts']} & {row['rescues']} & {row['rescue_probability']:.3f} & "
                f"{row['mean_completion_tokens']:,} & {row['rescues_per_token_e5']:.2f} \\\\"
            )
        return "\n".join(out) + "\n"

    (TABLES / "retryability.tex").write_text(retry_table(dev_rows), encoding="utf-8")
    (TABLES / "retryability_all.tex").write_text(retry_table(all_rows), encoding="utf-8")

    order_rows = []
    for i, (d, a) in enumerate(zip(dv["frozen_class_order"], devret["class_order_fit_on_all83"]), 1):
        mark = "" if d == a else r"$\ast$"
        order_rows.append(f"{i} & {tex_escape(d.replace('_', ' '))}{mark} & "
                          f"{tex_escape(a.replace('_', ' '))} \\\\")
    (TABLES / "class_order_contrast.tex").write_text("\n".join(order_rows) + "\n",
                                                     encoding="utf-8")

    budget_rows = []
    for label, block in (("Block 1", mb1), ("Block 2", mb2)):
        for i, row in enumerate(block["matched_budget_slices"]):
            head = label if i == 0 else ""
            budget_rows.append(
                f"{head} & {pct(row['fraction_uniform_full_spend'], 0)} & "
                f"{row['budget_tokens']:,} & {row['uniform_solves']} & "
                f"{row['rules_solves']} & {row['rules_tokens_issued']:,} \\\\"
            )
        if label == "Block 1":
            budget_rows.append(r"\midrule")
    (TABLES / "scheduler_budget_slices.tex").write_text(
        "\n".join(budget_rows) + "\n", encoding="utf-8")

    pipeline_rows = []
    for label, key in (("Seed block 1", "block1"), ("Seed block 2", "block2")):
        block = e2e["blocks"][key]
        pipeline_rows.append(
            f"{label} & {block['total_verified_of_202']}/202 & "
            f"{block['uniform']['pipeline_calls']:,} & {block['rules']['pipeline_calls']:,} & "
            f"{block['uniform']['pipeline_completion_tokens']:,} & "
            f"{block['rules']['pipeline_completion_tokens']:,} & "
            f"{pct(block['pipeline_completion_token_savings_fraction'])} \\\\"
        )
    (TABLES / "scheduler_pipeline.tex").write_text(
        "\n".join(pipeline_rows) + "\n", encoding="utf-8")

    manifest = []
    for path in sorted(p for p in PROV.glob("*.json") if p.name != "DIGESTS.json"):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        manifest.append({"file": path.name, "sha256": digest})
    (PROV / "DIGESTS.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")

    print(f"wrote {len(macros)-1} macros, 6 tables, and {len(manifest)} provenance digests")


if __name__ == "__main__":
    main()
